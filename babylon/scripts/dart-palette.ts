// Reads the three art styles (colours, ink, glow, pixel) straight from
// rattleramp/lib/ui/theme.dart, so the web never re-types a palette.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const DART_THEME = fileURLToPath(new URL('../../rattleramp/lib/ui/theme.dart', import.meta.url));

export const COLOR_KEYS = ['night', 'rampFill', 'rampEdge', 'coping', 'skater', 'board', 'grip', 'perfect', 'good', 'late', 'miss', 'dim'] as const;
export type ColorKey = (typeof COLOR_KEYS)[number];

export interface DartStyle {
  label: string;
  /** ARGB ints, as in Dart. */
  colors: Record<ColorKey, number>;
  ink: number | null;
  glow: boolean;
  pixel: number;
}

function colorValue(expr: string, consts: Record<string, number>): number {
  const e = expr.trim().replace(/^const\s+/, '');
  const m = /^Color\(0x([0-9A-Fa-f]{8})\)$/.exec(e);
  if (m) return parseInt(m[1], 16);
  if (e === 'Colors.white') return 0xffffffff;
  if (e === 'Colors.black') return 0xff000000;
  if (e in consts) return consts[e];
  throw new Error(`Unsupported colour in theme.dart: ${expr}`);
}

export function parseDartTheme(src: string = readFileSync(DART_THEME, 'utf8')): Record<string, DartStyle> {
  const consts: Record<string, number> = {};
  for (const m of src.matchAll(/^const (_\w+) = Color\(0x([0-9A-Fa-f]{8})\);/gm)) consts[m[1]] = parseInt(m[2], 16);
  const labels: Record<string, string> = {};
  const en = /enum ArtStyle \{([\s\S]*?);/.exec(src);
  if (!en) throw new Error('ArtStyle enum not found');
  for (const m of en[1].matchAll(/(\w+)\('([^']+)'\)/g)) labels[m[1]] = m[2];
  const out: Record<string, DartStyle> = {};
  const blocks = [...src.matchAll(/ArtStyle\.(\w+): (?:const )?StyleSpec\(/g)];
  if (blocks.length === 0) throw new Error('styleSpecs not found');
  blocks.forEach((b, i) => {
    const start = b.index! + b[0].length;
    const end = i + 1 < blocks.length ? blocks[i + 1].index! : src.indexOf('};', start);
    const body = src.slice(start, end);
    const field = (k: string): string | null => {
      const m = new RegExp(`^\\s{4}${k}: (.+),$`, 'm').exec(body);
      return m ? m[1] : null;
    };
    const colors = {} as Record<ColorKey, number>;
    for (const k of COLOR_KEYS) {
      const v = field(k);
      if (v === null) throw new Error(`${b[1]}.${k} missing in theme.dart`);
      colors[k] = colorValue(v, consts);
    }
    const ink = field('ink');
    out[b[1]] = {
      label: labels[b[1]] ?? b[1].toUpperCase(),
      colors,
      ink: ink === null ? null : colorValue(ink, consts),
      glow: field('glow') === 'true',
      pixel: Number(field('pixel') ?? 1),
    };
  });
  return out;
}

/** ARGB int → '#RRGGBB', or 'rgba(r,g,b,a)' when not opaque. */
export function argbCss(c: number): string {
  const a = (c >>> 24) & 0xff;
  const rgb = c & 0xffffff;
  if (a === 0xff) return `#${rgb.toString(16).padStart(6, '0').toUpperCase()}`;
  return `rgba(${(c >>> 16) & 0xff},${(c >>> 8) & 0xff},${c & 0xff},${+(a / 255).toFixed(3)})`;
}

export function renderPalette(styles: Record<string, DartStyle>): string {
  const lines = ['// GENERATED by `npm run gen` from rattleramp/lib/ui/theme.dart. Do not edit.', 'export const STYLES = {'];
  for (const [id, s] of Object.entries(styles)) {
    lines.push(`  ${id}: {`, `    label: '${s.label}',`);
    for (const k of COLOR_KEYS) lines.push(`    ${k}: '${argbCss(s.colors[k])}',`);
    lines.push(`    ink: ${s.ink === null ? 'null' : `'${argbCss(s.ink)}'`},`, `    glow: ${s.glow},`, `    pixel: ${s.pixel},`, '  },');
  }
  lines.push('} as const;', '');
  return lines.join('\n');
}
